#!/usr/bin/env python3
"""Generate splash/font.h from a PSF2 console font.

The graphical splash draws its tagline and version with the same face the
console uses (Lat2-Terminus16, rootfs/etc/vconsole.conf), so the text looks the
same before and after the splash. Only printable ASCII and the middle dot the
tagline uses are emitted, as 8x16 one-bit rows. Glyph slots in a PSF are not
code points, so the font's Unicode table is what maps them. Stdlib only.

    python3 tools/gen-splash-font.py Lat2-Terminus16.psfu.gz > splash/font.h

Terminus is (c) Dimitar Zhekov, SIL Open Font License 1.1.
"""
import gzip
import struct
import sys

WANT = [chr(c) for c in range(32, 127)] + ["·"]


def load(path):
    raw = open(path, "rb").read()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    magic, _ver, hsize, flags, count, csize, h, w = struct.unpack("<8I", raw[:32])
    if magic != 0x864AB572 or w != 8 or h != 16:
        sys.exit("want an 8x16 PSF2 font")
    glyphs = [raw[hsize + i * csize: hsize + (i + 1) * csize] for i in range(count)]
    cmap = {}
    if flags & 1:  # Unicode table: UTF-8 sequences per glyph, 0xFF-terminated
        pos = hsize + count * csize
        for i in range(count):
            end = raw.index(b"\xff", pos)
            entry = raw[pos:end]
            pos = end + 1
            for seq in entry.split(b"\xfe")[0:1]:
                for ch in seq.decode("utf-8", "replace"):
                    cmap.setdefault(ch, i)
    return glyphs, cmap


def main():
    glyphs, cmap = load(sys.argv[1])
    print("/* Generated by tools/gen-splash-font.py from Lat2-Terminus16.")
    print("   Terminus is (c) Dimitar Zhekov, SIL Open Font License 1.1. */")
    print("#define FONT_W 8")
    print("#define FONT_H 16")
    print("/* FONT[0..94] is ASCII 32..126; FONT[95] is U+00B7 MIDDLE DOT. */")
    print("static const unsigned char FONT[%d][16] = {" % len(WANT))
    for ch in WANT:
        g = glyphs[cmap.get(ch, cmap.get("?", 0))]
        print("    {%s}, /* %r */" % (", ".join("0x%02x" % b for b in g), ch))
    print("};")


if __name__ == "__main__":
    main()
